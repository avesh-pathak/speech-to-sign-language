"""Central configuration for the Telugu speech-to-ISL framework.

Every path is derived from the repository root so the project can be cloned
anywhere and launched with ``python app.py``.  The ``S2SL_DATA_DIR`` and
``S2SL_MODELS_DIR`` environment variables can be used to keep large corpora
outside the repository.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

PACKAGE_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = PACKAGE_DIR.parent

DATASETS_DIR = Path(os.environ.get("S2SL_DATA_DIR", PROJECT_ROOT / "data")).expanduser()
MODELS_ROOT = Path(os.environ.get("S2SL_MODELS_DIR", PROJECT_ROOT / "models")).expanduser()


@dataclass(frozen=True)
class Paths:
    """All filesystem locations used by the application."""

    root: Path = PROJECT_ROOT
    data: Path = DATASETS_DIR
    mappings: Path = DATASETS_DIR / "mappings"
    audio: Path = DATASETS_DIR / "audio"
    gifs: Path = DATASETS_DIR / "gifs"
    isl_corpus: Path = DATASETS_DIR / "ISL_Corpus"
    isl_frames: Path = DATASETS_DIR / "ISL_Corpus" / "Frames_Word_Level"
    models: Path = MODELS_ROOT
    trained: Path = MODELS_ROOT / "trained"

    # Curated mapping shipped with the repository.
    telugu_to_isl: Path = DATASETS_DIR / "mappings" / "telugu_to_isl.json"

    # Files generated by ``python app.py --mode prepare``.
    isl_signs: Path = DATASETS_DIR / "mappings" / "isl_corpus_signs.json"
    isl_index: Path = DATASETS_DIR / "mappings" / "isl_corpus_index.json"
    isl_corpus_mapping: Path = DATASETS_DIR / "mappings" / "telugu_to_isl_corpus.json"

    # Training artefacts.
    trained_model: Path = MODELS_ROOT / "trained" / "res_bilstm_am_best.keras"
    class_mapping: Path = MODELS_ROOT / "trained" / "class_mapping.json"


PATHS = Paths()

