def ensure_directories() -> None:
    """Create the writable directories used at runtime (idempotent)."""
    for path in (
        PATHS.data,
        PATHS.mappings,
        PATHS.audio,
        PATHS.gifs,
        PATHS.isl_corpus,
        PATHS.isl_frames,
        PATHS.models,
        PATHS.trained,
    ):
        path.mkdir(parents=True, exist_ok=True)
